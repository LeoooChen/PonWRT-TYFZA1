static inline bool rtl_ax_vendor_match(const u8 *address, const u8 table[][3], unsigned int entries)
{
	for (unsigned int i = 0; i < entries; i++)
		if (!memcmp(address, table[i], 3)) return true;
	return false;
}
#define RTL_AX_VENDOR_MATCH(p, name) rtl_ax_vendor_match(p, rtl_ax_##name##_oui, ARRAY_SIZE(rtl_ax_##name##_oui))
static inline u8 rtl_ax_vendor(const u8 *address, const u8 *ies, unsigned int bytes)
{
	if (RTL_AX_VENDOR_MATCH(address, octoscope)) return 21;
	if (RTL_AX_VENDOR_MATCH(address, qingdao_pda)) return 22;
	if (RTL_AX_VENDOR_MATCH(address, fibocom_pda)) return 23;
	for (unsigned int at = 0; at + 2 <= bytes;) {
		unsigned int len = ies[at + 1];
		if (at + 2 + len > bytes) break;
		if (ies[at] == 221 && len >= 3) {
			if (RTL_AX_VENDOR_MATCH(ies + at + 2, broadcom)) return 3;
			if (RTL_AX_VENDOR_MATCH(ies + at + 2, qualcomm)) return 20;
		}
		at += len + 2;
	}
	if (RTL_AX_VENDOR_MATCH(address, apple)) return 18;
	if (RTL_AX_VENDOR_MATCH(address, veriwave)) return 19;
	return 0;
}
